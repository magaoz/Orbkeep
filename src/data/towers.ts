function path(
  names: [string, string, string, string],
  descs: [string, string, string, string],
  costs: [number, number, number, number],
  mods: Partial<UpgradeTier>[],
): UpgradeTier[] {
  return names.map((name, i) => ({
    name,
    desc: descs[i],
    cost: costs[i],
    ...mods[i],
  }))
}

